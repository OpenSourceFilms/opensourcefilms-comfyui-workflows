"""Real pinned VHS 8-bit default versus opt-in 16-bit RGB input acceptance.

The test-only ComfyUI IMAGE tensor is generated by a disposable fixture.
The two temporary ProRes 4444 outputs differ only by input_color_depth
in a CI-only preset copied from the exactly pinned upstream configuration.

This is a narrow two-frame RGB-to-YUV precision test, NOT colour-managed
camera fidelity or a reusable production media transform.
"""
from __future__ import annotations

from array import array
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time
from urllib.parse import urlencode
from urllib.request import Request, urlopen


FORMAT_NAME = "osf_ci_prores16bit"
PIXELS = 64 * 64
FRAME_COMPONENTS = 3 * PIXELS
BYTE_LENGTH = 2 * FRAME_COMPONENTS * 2
MAX_BYTES = 2_000_000
EXPECTED_PAIR_COUNT = 4


def prepare_disposable_16bit_preset(comfy: Path) -> dict:
    """Make exactly one CI-only untracked variant; leave upstream preset intact."""
    base = comfy / "custom_nodes" / "ComfyUI-VideoHelperSuite" / "video_formats"
    original = base / "ProRes.json"
    target = base / (FORMAT_NAME + ".json")
    if (base.is_symlink() or original.is_symlink()
            or not original.is_file() or target.exists() or target.is_symlink()):
        raise ValueError("Unsafe/missing disposable VHS precision format")
    upstream = original.read_bytes()
    definition = json.loads(upstream)
    if (not isinstance(definition, dict)
            or definition.get("extension") != "mov"
            or "prores_ks" not in str(definition.get("main_pass"))
            or "input_color_depth" in definition
            or "4444" not in str(definition.get("extra_widgets"))):
        raise ValueError("Pinned upstream ProRes configuration differs")
    local = {**definition, "input_color_depth": "16bit"}
    with target.open("x", encoding="utf-8") as out:
        json.dump(local, out, sort_keys=True)
    # Must not mutate the exact pinned upstream preset.
    if original.read_bytes() != upstream:
        raise ValueError("Upstream VHS ProRes preset was altered")
    return {
        "based_on_upstream_preset_sha256": hashlib.sha256(upstream).hexdigest(),
        "additional_preset": FORMAT_NAME,
        "sole_override": {"input_color_depth": "16bit"},
        "upstream_default_8bit_intact": True,
        "disposable_runner_only": True,
    }


def build_precision_prompt() -> dict:
    common = {
        "images": ["1", 0], "frame_rate": 2, "loop_count": 0,
        "profile": "4444", "pingpong": False, "save_output": False,
    }
    return {
        "1": {"class_type": "OSFTestPrecisionFrames", "inputs": {}},
        "2": {"class_type": "VHS_VideoCombine", "inputs": {
            **common, "format": "video/ProRes",
            "filename_prefix": "osf_ci_precision_default8",
        }},
        "3": {"class_type": "VHS_VideoCombine", "inputs": {
            **common, "format": "video/" + FORMAT_NAME,
            "filename_prefix": "osf_ci_precision_optin16",
        }},
    }


def _validated_asset(entry: object, expected_format: str) -> dict:
    if (not isinstance(entry, dict)
            or entry.get("format") != expected_format
            or entry.get("type") != "temp"
            or entry.get("subfolder") not in (None, "")):
        raise ValueError("Unexpected VHS temporary precision output")
    name = entry.get("filename")
    if (not isinstance(name, str)
            or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,175}\.mov", name)):
        raise ValueError("Unsafe precision output filename")
    return {"filename": name, "type": "temp", "subfolder": ""}


def validate_precision_history(history: object, prompt_id: str) -> tuple[dict, dict]:
    if not isinstance(history, dict) or not isinstance(history.get(prompt_id), dict):
        raise ValueError("Missing VHS precision prompt history")
    entry = history[prompt_id]
    status = entry.get("status")
    if (not isinstance(status, dict)
            or status.get("completed") is not True
            or status.get("status_str") != "success"):
        raise ValueError("VHS precision prompt did not complete")
    outputs = entry.get("outputs")
    if not isinstance(outputs, dict):
        raise ValueError("VHS precision graph missing outputs")
    items = []
    for key, format_name in (("2", "video/ProRes"),
                             ("3", "video/" + FORMAT_NAME)):
        output = outputs.get(key)
        videos = output.get("gifs") if isinstance(output, dict) else None
        if not isinstance(videos, list) or len(videos) != 1:
            raise ValueError("VHS precision graph missing one required MOV")
        items.append(_validated_asset(videos[0], format_name))
    if items[0]["filename"] == items[1]["filename"]:
        raise ValueError("VHS precision graph reused an output filename")
    return items[0], items[1]


def _read_mov(port: int, entry: dict) -> bytes:
    query = urlencode(entry)
    with urlopen("http://127.0.0.1:" + str(port) + "/view?" + query,
                 timeout=10) as response:
        if response.status != 200:
            raise ValueError("VHS precision MOV download failed")
        raw = response.read(MAX_BYTES + 1)
    if not 12 <= len(raw) <= MAX_BYTES or raw[4:8] != b"ftyp":
        raise ValueError("Invalid or oversized VHS precision MOV")
    return raw


def _decode_12bit_mov(data: bytes) -> tuple[array, dict]:
    from imageio_ffmpeg import get_ffmpeg_exe
    with tempfile.TemporaryDirectory(prefix="osf_vhs_16bit_") as temp:
        mov = Path(temp) / "frames.mov"
        mov.write_bytes(data)
        decoded = subprocess.run(
            [get_ffmpeg_exe(), "-hide_banner", "-nostdin",
             "-i", str(mov), "-map", "0:v:0", "-fps_mode", "passthrough",
             "-pix_fmt", "yuv444p12le", "-f", "rawvideo", "pipe:1"],
            capture_output=True, check=True, timeout=30,
        )
    stderr = decoded.stderr.decode("utf-8", "replace")
    if (not re.search(r"Video:\s+prores\s+\(4444\)\s", stderr, re.I)
            or not re.search(r"\byuv444p12le\b", stderr)):
        raise ValueError("VHS precision MOV is not ProRes 4444 12-bit 4:4:4")
    if len(decoded.stdout) != BYTE_LENGTH:
        raise ValueError("VHS precision MOV decoded wrong frame count/size")
    samples = array("H")
    samples.frombytes(decoded.stdout)
    if samples.itemsize != 2:
        raise RuntimeError("Unsupported uint16 host")
    if sys.byteorder != "little":
        samples.byteswap()
    if len(samples) != 2 * FRAME_COMPONENTS or any(n > 4095 for n in samples):
        raise ValueError("VHS precision MOV has invalid 12-bit samples")
    return samples, {
        "encoded_mov_sha256": hashlib.sha256(data).hexdigest(),
        "encoded_mov_size_bytes": len(data),
    }


def _pairs(samples: array) -> list[tuple[int, int]]:
    pairs = []
    for frame in range(2):
        for row in range(2):
            offset = frame * FRAME_COMPONENTS + (row * 32 + 16) * 64
            pairs.append((samples[offset + 16], samples[offset + 48]))
    return pairs


def verify_precision_contrast(default8: array, optin16: array) -> dict:
    if (len(default8) != 2 * FRAME_COMPONENTS
            or len(optin16) != 2 * FRAME_COMPONENTS):
        raise ValueError("VHS precision decoded sample count incorrect")
    a = _pairs(default8)
    b = _pairs(optin16)
    if len(a) != EXPECTED_PAIR_COUNT or len(b) != EXPECTED_PAIR_COUNT:
        raise ValueError("VHS precision comparisons incomplete")
    if any(left != right for left, right in a):
        raise ValueError("VHS default 8-bit control did not quantize source pairs")
    deltas = [right - left for left, right in b]
    if any(not 1 <= change <= 20 for change in deltas):
        raise ValueError("VHS opt-in 16-bit path did not retain fine source levels")
    return {
        "status": "vhs_16bit_input_sub8bit_levels_preserved",
        "source": "synthetic 12-bit-indexed RGB float IMAGE",
        "codec": "prores_ks",
        "profile": "4444",
        "storage_format": "yuv444p12le",
        "default_8bit_collapsed_pairs": len(a),
        "optin16_preserved_pairs": len(b),
        "optin16_luma_code_level_deltas": deltas,
        "frames": 2,
        "dimensions": [64, 64],
        "sample_count_per_output": 2 * FRAME_COMPONENTS,
        "model_weights_used": False,
        "camera_color_management_qualified": False,
        "bit_exact_source_fidelity_qualified": False,
        "binary_outputs_uploaded": False,
    }


def execute_disposable_vhs_precision(port: int, child, timeout_seconds: int = 70) -> dict:
    prompt = build_precision_prompt()
    req = Request(
        "http://127.0.0.1:" + str(port) + "/prompt",
        data=json.dumps({"prompt": prompt}).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urlopen(req, timeout=12) as resp:
        if resp.status != 200:
            raise ValueError("ComfyUI rejected VHS precision prompt")
        submitted = json.loads(resp.read(100_000))
    ident = submitted.get("prompt_id") if isinstance(submitted, dict) else None
    if not isinstance(ident, str) or not ident or len(ident) > 100:
        raise ValueError("VHS precision prompt id invalid")
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline:
        if child.poll() is not None:
            raise RuntimeError("ComfyUI exited before VHS precision graph finished")
        with urlopen("http://127.0.0.1:" + str(port) + "/history/" + ident,
                     timeout=8) as resp:
            if resp.status != 200:
                raise RuntimeError("VHS precision history status invalid")
            history = json.loads(resp.read(200_000))
        if isinstance(history, dict) and ident in history:
            original, precise = validate_precision_history(history, ident)
            default_data = _read_mov(port, original)
            precise_data = _read_mov(port, precise)
            a, a_meta = _decode_12bit_mov(default_data)
            b, b_meta = _decode_12bit_mov(precise_data)
            result = verify_precision_contrast(a, b)
            return {
                **result,
                "default8_mov": a_meta,
                "optin16_mov": b_meta,
            }
        time.sleep(1)
    raise TimeoutError("VHS precision API graph exceeded bounded timeout")
